#!/usr/bin/env python3
"""Generates Sources/DeviceCatalog.swift from two open-source descriptions of HeyMelody models.

  python3 tools/generate_catalog.py <BluetoothOpoDeviceProfile.kt> <oppo_ctl.py> > Sources/DeviceCatalog.swift

- BluetoothOpoDeviceProfile.kt: RawS-Music (Apache-2.0), generated from HeyMelody's bundled device
  whitelist. Gives each model's name, brand, noise modes (bit -> modeType), EQ presets and features.
  https://github.com/QFDY-GZC/RawS-Music
- oppo_ctl.py: the Noctalia oppo-pods plugin (MIT, Copyright (c) 2026 osp54). Gives the noise-mode bit
  layouts used when *setting* a mode (proven on real buds) and the realme product IDs.
  https://github.com/noctalia-dev/community-plugins/tree/main/oppo-pods
"""
import ast
import re
import sys

profile_src = open(sys.argv[1], encoding="utf-8").read()
ctl_src = open(sys.argv[2], encoding="utf-8").read()


def py_literal(name):
    """Reads a top-level `NAME = {...}` literal from oppo_ctl.py (comments stripped)."""
    m = re.search(rf"^{name} = (\{{[^\n]*\}})\s*(#[^\n]*)?$", ctl_src, re.M)  # one-line literal
    if not m:
        m = re.search(rf"^{name} = (\{{.*?^\}})", ctl_src, re.S | re.M)
    body = re.sub(r"#[^\n]*", "", m.group(1))
    return ast.literal_eval(body)


ctl_layouts = py_literal("NOISE_LAYOUTS")
realme_ids = py_literal("REALME_PRODUCT_IDS")
realme_layout = py_literal("REALME_NOISE_LAYOUT")

# HeyMelody whitelist feature keys -> catalog features.
FEATURE_KEYS = {
    "noiseReductionMode": "noiseControl",
    "equalizer": "equalizer",
    "equalizerMode": "equalizer",
    "customEqualizer": "customEQ",
    "gameMode": "lowLatency",
    "heyFindDevice": "findBuds",
    "findDevice": "findBuds",
    "control": "gestures",
}

# Reported-bit quirks seen on real buds that the whitelist doesn't describe.
# Buds Pro 3 report their ANC levels in bits 12-15 (from PR #3 by Bhanu, tested on the buds).
EXTRA_REPORTED_BITS = {"064014": {12: 4, 13: 8, 14: 3, 15: 7}}

models = {}
for block in re.split(r"\n\s*Profile\(", profile_src)[1:]:
    pid = re.search(r'productIdHex = "([0-9A-F]+)"', block).group(1)
    name = re.search(r'modelName = "([^"]*)"', block).group(1)
    brand = re.search(r'brand = "([^"]*)"', block).group(1).lower()
    keys = set(re.findall(r'"(\w+)"', re.search(r"enabledFunctionKeys = setOf\(([^)]*)\)", block).group(1)))
    anc = re.search(r"ancModes = listOf\((.*?)\n\s*\),", block, re.S)
    modes = []
    if anc:
        for bit, mtype, rest in re.findall(r"AncMode\((\d+), (\d+), \"[^\"]*\"([^)]*)\)", anc.group(1)):
            if "decideByEarDevice = true" not in rest:  # only offered when the buds decide; skip
                modes.append((int(bit), int(mtype)))
    eq = re.search(r"eqPresets = listOf\((.*?)\n\s*\),", block, re.S)
    presets = [(int(i), int(t)) for i, t in re.findall(r"EqPreset\((\d+), (\d+),", eq.group(1))] if eq else []
    features = sorted({FEATURE_KEYS[k] for k in keys if k in FEATURE_KEYS})
    models[pid] = dict(name=name, brand=brand, modes=modes, presets=presets, features=features, known=True)

# Models only oppo-pods knows about, and realme (one shared layout, not in HeyMelody's whitelist).
for pid in ctl_layouts:
    models.setdefault(pid, dict(name="", brand="oneplus" if pid.endswith("14") else "oppo", modes=[], presets=[],
                                features=[], known=False))
for pid in sorted(realme_ids):
    models.setdefault(pid, dict(name="", brand="realme", modes=[], presets=[], features=[], known=False))


def swift_map(d):
    return "[" + ", ".join(f"{k}: {v}" for k, v in sorted(d.items())) + "]" if d else "[:]"


def write_layout(pid, m):
    if pid in ctl_layouts:
        return ctl_layouts[pid]
    if m["brand"] == "realme":
        return realme_layout
    return {}


print("""// Generated by tools/generate_catalog.py. Do not edit by hand; re-run the script instead.
//
// Model data derived from:
// - RawS-Music's HeyMelody device profiles (Apache License 2.0), https://github.com/QFDY-GZC/RawS-Music
// - the Noctalia oppo-pods plugin (MIT, Copyright (c) 2026 osp54),
//   https://github.com/noctalia-dev/community-plugins/tree/main/oppo-pods
// See THIRD_PARTY_NOTICES.md.

extension DeviceCatalog {
    static let models: [String: DeviceModel] = [""")
for pid in sorted(models):
    m = models[pid]
    shown = sorted({t for _, t in m["modes"]}) or sorted(set(write_layout(pid, m).values()))
    read = {}
    read.update(write_layout(pid, m))
    for b, t in m["modes"]:
        if b in read and read[b] != t:
            print(f"conflict {pid} bit {b}: set layout {read[b]} vs whitelist {t}", file=sys.stderr)
    read.update({b: t for b, t in m["modes"]})
    read.update(EXTRA_REPORTED_BITS.get(pid, {}))
    presets = ", ".join(f"({i}, {t})" for i, t in m["presets"])
    # nil = this source doesn't say which features the model has; the buds' own replies decide.
    feats = "[" + ", ".join("." + f for f in m["features"]) + "]" if m["known"] else "nil"
    print(f'        "{pid}": DeviceModel(name: "{m["name"]}", brand: .{m["brand"]},')
    print(f"                             modeTypes: {shown},")
    print(f"                             setBits: {swift_map(write_layout(pid, m))},")
    print(f"                             reportedBits: {swift_map(read)},")
    print(f"                             eqPresets: [{presets}],")
    print(f"                             features: {feats}),")
print("""    ]
}""")
print(f"// {len(models)} models", file=sys.stderr)
